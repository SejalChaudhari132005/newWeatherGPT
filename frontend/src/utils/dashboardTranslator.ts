/**
 * Translate Air Quality Category (e.g. "GOOD", "POOR", "Moderate")
 */
export function translateAQICategory(category: string, lang: LanguageCode): string {
  if (!category) return '';
  const key = category.toUpperCase().trim();
  if (AQI_CATEGORIES_MAP[key] && AQI_CATEGORIES_MAP[key][lang]) {
    return AQI_CATEGORIES_MAP[key][lang]!;
  }
  return category;
}

/**
 * Translate Air Quality Trend (e.g. "IMPROVING", "STABLE", "WORSENING")
 */
export function translateAQITrend(trend: string, lang: LanguageCode): string {
  if (!trend) return '';
  const key = trend.toUpperCase().trim();
  if (AQI_TRENDS_MAP[key] && AQI_TRENDS_MAP[key][lang]) {
    return AQI_TRENDS_MAP[key][lang]!;
  }
  return trend;
}

/**
 * Translate Pollutant Name or Code (e.g. "pm2_5", "PM2.5", "no2")
 */
export function translatePollutant(codeOrName: string, lang: LanguageCode): string {
  if (!codeOrName) return '';
  const clean = codeOrName.toLowerCase().replace('.', '_').replace(/\s+/g, '_').trim();
  for (const [codeKey, langMap] of Object.entries(POLLUTANT_NAMES_MAP)) {
    if (clean.includes(codeKey) || codeOrName.toLowerCase().includes(codeKey.replace('_', ''))) {
      if (langMap[lang]) return langMap[lang]!;
    }
  }
  return codeOrName;
}

/**
 * Translate standard outdoor advisory based on category
 */
export function translateAirAdvisory(category: string, originalText: string, lang: LanguageCode): string {
  if (lang === 'en') return originalText;
  const key = `${category.toUpperCase().trim()}_OUTDOOR`;
  if (AIR_ADVISORY_MAP[key] && AIR_ADVISORY_MAP[key][lang]) {
    return AIR_ADVISORY_MAP[key][lang]!;
  }
  return originalText;
}

/**
 * Translate weather condition string (e.g. "Light Drizzle", "Rain", "Clear Sky")
 */
export function translateCondition(condition: string, lang: LanguageCode): string {
  if (!condition || lang === 'en') return condition || 'Clear Sky';
  const key = condition.toLowerCase().trim();
  if (WEATHER_CONDITIONS_MAP[key] && WEATHER_CONDITIONS_MAP[key][lang]) {
    return WEATHER_CONDITIONS_MAP[key][lang]!;
  }
  // Partial substring matching
  for (const [condKey, langMap] of Object.entries(WEATHER_CONDITIONS_MAP)) {
    if (key.includes(condKey) && langMap[lang]) {
      return langMap[lang]!;
    }
  }
  return condition;
}

/**
 * Translate UI phrase by key
 */
export function translatePhrase(key: string, lang: LanguageCode): string {
  if (UI_PHRASES[key] && UI_PHRASES[key][lang]) {
    return UI_PHRASES[key][lang];
  }
  return UI_PHRASES[key]?.en || key;
}

